#include <iostream>
#include <string>
using namespace std;

int main() {
    int x, n;
    cin >> x >> n; // x - первое число, n - сколько элементов нужно получить

    string current = to_string(x); // Превращаем число в строку, с ней проще работать

    // Нам нужно сделать n-1 шагов, чтобы получить n-й элемент
    for (int step = 1; step < n; step++) {
        string next = ""; // Сюда будем собирать новый элемент последовательности
        int len = current.length();
        int i = 0; // Индекс текущей цифры в строке

        while (i < len) {
            char digit = current[i]; // Запоминаем, какая цифра сейчас
            int count = 1; // Считаем её (минимум 1 раз она есть)

            // Смотрим вперед: если следующая цифра такая же, увеличиваем счетчик
            while (i + 1 < len && current[i + 1] == digit) {
                count++;
                i++; // Переходим к следующей такой же цифре
            }

            // Добавляем в результат: сначала сколько раз, потом саму цифру
            next += to_string(count);
            next += digit;

            i++; // Переходим к следующей новой цифре
        }

        current = next; // Теперь эта новая строка становится текущей для следующего шага
    }

    cout << current << endl; // Выводим итоговую строку
    return 0;
}
