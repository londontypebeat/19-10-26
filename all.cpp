#include <iostream>
using namespace std;

int main() {
    int N;
    cin >> N;  // Вводим размер квадрата

    // Проходим по каждой строке
    for (int i = 0; i < N; i++) {
        // Проходим по каждому столбцу в строке
        for (int j = 0; j < N; j++) {
            // Если сумма индексов меньше N-1 — это выше побочной диагонали
            if (i + j < N - 1) {
                cout << 0;
            }
            // Если равна N-1 — это сама побочная диагональ
            else if (i + j == N - 1) {
                cout << 1;
            }
            // Если больше — это ниже диагонали
            else {
                cout << 2;
            }

            // Ставим пробел, если это не последний элемент в строке
            if (j != N - 1) {
                cout << " ";
            }
        }
        cout << endl;  // Переход на новую строку после вывода всей строки матрицы
    }
    return 0;
}
