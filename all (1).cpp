#include <iostream>

using namespace std;

// Создаём большое поле с запасом. 
// false = пусто, true = гриб.
// Глобальные переменные сразу становятся false (пустыми), нам не надо их обнулять.
bool field[40][40];

int main() {
    int n, m, w;
    cin >> n >> m >> w; // Читаем размеры и кол-во грибов

    // 1. Сначала просто ставим грибы на поле
    for (int k = 0; k < w; k++) {
        int r, c;
        cin >> r >> c;
        // В задаче считают с 1, а в массиве с 0, поэтому отнимаем 1
        field[r - 1][c - 1] = true;
    }

    // 2. Теперь проходим по КАЖДОЙ клетке поля и решаем, что печатать
    for (int i = 0; i < n; i++) { // идём по строкам
        for (int j = 0; j < m; j++) { // идём по столбцам

            // Если в этой клетке гриб — сразу печатаем *
            if (field[i][j]) {
                cout << "*";
            } else {
                // Если клетка пустая — считаем грибы вокруг
                int count = 0; // Сначала грибов рядом 0

                // Проверяем всех 8 соседей вручную
                // Просто перебираем все варианты смещения: -1, 0, +1
                for (int di = -1; di <= 1; di++) {
                    for (int dj = -1; dj <= 1; dj++) {

                        // Пропускаем саму клетку, нам нужны только соседи
                        if (di == 0 && dj == 0) continue;

                        int ni = i + di; // Координата соседа по строке
                        int nj = j + dj; // Координата соседа по столбцу

                        // ГЛАВНОЕ: сначала проверяем, не вышли ли мы за границы поля!
                        if (ni >= 0 && ni < n && nj >= 0 && nj < m) {
                            // Если сосед внутри поля, смотрим, есть ли там гриб
                            if (field[ni][nj]) {
                                count++;
                            }
                        }
                    }
                }

                // Печатаем посчитанное число
                cout << count;
            }
        }
        cout << endl; // Конец строки
    }

    return 0;
}